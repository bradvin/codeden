import { z } from "zod";
import { parseTrustedOrigin } from "./network";

/**
 * Other CodeDen servers in the desktop app (§17): the app can open a CodeDen server running on
 * another machine, such as one behind Tailscale Serve, in a window of its own. The list belongs
 * to the desktop app (`<home>/desktop/servers.json`), never to a server's settings. "This Mac"
 * is the app's own server: implicit, always first, never stored.
 */

/** The id of the app's own server ("This Mac"). Remote ids never take this value. */
export const LOCAL_SERVER_ID = "local";

/** Most remote servers the list holds. */
export const REMOTE_SERVERS_MAX = 20;

/** A remote server's id: generated by the app, used in a session partition name and file names. */
export const RemoteServerId = z
  .string()
  .regex(/^[a-z0-9]{6,32}$/)
  .refine((id) => id !== LOCAL_SERVER_ID);

/** The name shown in the header chip, menus and tray. */
export const RemoteServerName = z.string().trim().min(1).max(60);

/** The address of a remote server as stored: the normalized `https://host[:port]` origin. */
export const RemoteServerUrl = z.string().transform((value, ctx) => {
  const parsed = parseRemoteServerUrl(value);
  if (!parsed.ok) {
    ctx.addIssue({ code: "custom", message: parsed.problem });
    return z.NEVER;
  }
  return parsed.origin;
});

/**
 * Check a remote server's address. Same rules as a trusted origin (§15.1): `https://<dns
 * name>[:port]`, no path, query, credentials or IP address, so a bad certificate can never be
 * the only thing standing between the app and the server. Returns the normalized origin.
 */
export function parseRemoteServerUrl(
  input: string,
): { ok: true; origin: string } | { ok: false; problem: string } {
  const parsed = parseTrustedOrigin(input);
  if (!parsed.ok && parsed.problem.startsWith("That is this computer")) {
    return { ok: false, problem: "That is this computer; use This Mac." };
  }
  return parsed;
}

/** A remote server in the desktop app's list. */
export const RemoteServer = z.object({
  id: RemoteServerId,
  name: RemoteServerName,
  url: RemoteServerUrl,
});
export type RemoteServer = z.infer<typeof RemoteServer>;

/**
 * `<home>/desktop/servers.json`. Recovery for a hand-edited file: an entry that fails
 * validation (or repeats an id or address) is dropped, never the whole list.
 */
export const RemoteServersFile = z.object({
  servers: z
    .unknown()
    .transform((value): RemoteServer[] => {
      if (!Array.isArray(value)) return [];
      const kept: RemoteServer[] = [];
      for (const entry of value) {
        const parsed = RemoteServer.safeParse(entry);
        if (!parsed.success) continue;
        if (kept.some((s) => s.id === parsed.data.id || s.url === parsed.data.url)) continue;
        kept.push(parsed.data);
      }
      return kept.slice(0, REMOTE_SERVERS_MAX);
    })
    .default([]),
});
export type RemoteServersFile = z.infer<typeof RemoteServersFile>;

/** Which server a desktop window shows, as `DesktopInfo.server` tells the UI. */
export const DesktopServerRef = z.object({
  /** `LOCAL_SERVER_ID` for This Mac, else the remote server's id. */
  id: z.string(),
  name: z.string(),
  /** A window on another machine's server: the UI behaves as in a normal browser. */
  remote: z.boolean(),
});
export type DesktopServerRef = z.infer<typeof DesktopServerRef>;

/** Where a remote server's last background check stands (tray, badge). */
export const RemoteServerState = z.enum(["connecting", "ok", "signed-out", "unreachable"]);
export type RemoteServerState = z.infer<typeof RemoteServerState>;

/** The answer to adding a server in the manager window. */
export const AddServerResult = z.discriminatedUnion("ok", [
  z.object({
    ok: z.literal(true),
    server: RemoteServer,
    /** A different CodeDen version: worth knowing, never a reason to refuse. */
    warning: z.string().nullable(),
  }),
  z.object({ ok: z.literal(false), problem: z.string() }),
]);
export type AddServerResult = z.infer<typeof AddServerResult>;

/** One row of the manager window. */
export const ServerRow = z.object({
  id: z.string(),
  name: z.string(),
  /** Null for This Mac. */
  url: z.string().nullable(),
  state: RemoteServerState.nullable(),
});
export type ServerRow = z.infer<typeof ServerRow>;

/**
 * `window.codedenServers`: exposed to the app's own "Manage servers" window only (a static page
 * shipped with the app), never to a server's page.
 */
export interface CodedenServersApi {
  list(): Promise<ServerRow[]>;
  add(name: string, url: string): Promise<AddServerResult>;
  rename(id: string, name: string): Promise<{ ok: boolean; problem?: string }>;
  /** Removes the entry, closes its window and clears its stored session data. */
  remove(id: string): Promise<{ ok: boolean }>;
  open(id: string): void;
  onChange(listener: (rows: ServerRow[]) => void): () => void;
}
